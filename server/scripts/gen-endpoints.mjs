// Generates src/.generated/endpoints.ts — the registry of every endpoint in src/api.
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const names = readdirSync(resolve(root, 'src/api')).filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts')).map((f) => f.slice(0, -3)).sort();
mkdirSync(resolve(root, 'src/.generated'), { recursive: true });
writeFileSync(
  resolve(root, 'src/.generated/endpoints.ts'),
  `// generated by scripts/gen-endpoints.mjs — do not edit\n` +
    names.map((n, i) => `import e${i} from '../api/${n}';`).join('\n') +
    `\nexport default {\n${names.map((n, i) => `  ${n}: e${i},`).join('\n')}\n};\n`,
);
console.log(`registered ${names.length} endpoints`);
